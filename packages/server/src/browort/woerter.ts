/**
 * Wortlisten fuer Browort und Clanwort (Emile, 23.10.2026: „Eigene Liste").
 *
 * Selbst geschrieben statt aus dem Netz geladen: keine Lizenzfrage, und jede
 * Loesung ist ein Wort, das man im Alltag kennt. Zwei Listen mit zwei
 * Aufgaben:
 *
 * - `LOESUNGEN` sind die Woerter, die als Tageswort drankommen koennen —
 *   gaengig, ohne Eigennamen, ohne Anstoessiges, ohne Abkuerzungen.
 * - `ERLAUBT` sind alle Woerter, die man raten DARF: die Loesungen plus
 *   Beugungsformen und seltenere Woerter. Was hier fehlt, weist der Server
 *   als „Kenne ich nicht" ab, ohne dass ein Versuch verbraucht ist.
 *
 * Beide Listen bleiben auf dem Server. Kaeme die Loesungsliste ins App-Paket,
 * liesse sich das Tageswort aus ihr und dem Datum ausrechnen.
 *
 * Schreibweise: Grossbuchstaben, genau fuenf Zeichen, Umlaute als eigene
 * Buchstaben, kein ß (es gibt dafuer keine Taste — „Spass" statt „Spaß"
 * waere falsch geschrieben, also fehlen solche Woerter ganz). Geprueft in
 * test/browort.test.ts.
 */

function liste(text: string): string[] {
  return text
    .split(/\s+/)
    .map((wort) => wort.trim())
    .filter((wort) => wort.length > 0);
}

