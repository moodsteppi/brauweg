/** Alles, was geraten werden darf. */
export const ERLAUBT: ReadonlySet<string> = new Set(
  [...LOESUNGEN, ...NUR_ERLAUBT].filter((wort) => wortGueltig(wort)),
);

/** Fuenf Buchstaben A–Z oder Umlaut, sonst nichts. */
export function wortGueltig(wort: string): boolean {
  return /^[A-ZÄÖÜ]{5}$/.test(wort);
}
